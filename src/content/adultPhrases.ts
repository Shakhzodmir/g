/** Tags the base adult phrases (pain scale included) with their category. */
export function withAdultGroups(list: Phrase[]): Phrase[] {
  return list.map((p) => {
    if (p.audience !== 'adult' || p.group) return p
    const group = BASE_GROUP[p.id] ?? (/^pain_\d+$/.test(p.id) ? 'pain' : undefined)
    return group ? { ...p, group } : p
  })
}

