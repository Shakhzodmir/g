// Copies only the latin, latin-ext, cyrillic and cyrillic-ext subsets of the three variable fonts
// into src/design/fonts and writes src/design/fonts.css with the exact unicode-ranges from Fontsource.
// Run: node scripts/copy-fonts.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'src', 'design', 'fonts')
const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext']
const FAMILIES = [
  { pkg: 'nunito', file: 'nunito', family: 'Nunito Variable' },
  { pkg: 'onest', file: 'onest', family: 'Onest Variable' },
]

mkdirSync(outDir, { recursive: true })
let css = '/* Generated by scripts/copy-fonts.mjs. Fonts: SIL Open Font License 1.1. */\n'
for (const f of FAMILIES) {
  const pkgDir = join(root, 'node_modules', '@fontsource-variable', f.pkg)
  const index = readFileSync(join(pkgDir, 'index.css'), 'utf8')
  const blocks = index.split('@font-face').slice(1)
  for (const sub of SUBSETS) {
    const fileName = `${f.file}-${sub}-wght-normal.woff2`
    const block = blocks.find((b) => b.includes(`/${fileName}`))
    if (!block) throw new Error(`subset ${sub} not found for ${f.pkg}`)
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1]
    const weight = /font-weight:\s*([^;]+);/.exec(block)?.[1] ?? '100 900'
    if (!range) throw new Error(`unicode-range missing for ${fileName}`)
    copyFileSync(join(pkgDir, 'files', fileName), join(outDir, fileName))
    css += `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url('./fonts/${fileName}') format('woff2-variations');
  unicode-range: ${range};
}
`
  }
}
writeFileSync(join(root, 'src', 'design', 'fonts.css'), css)
console.log('fonts.css written')
